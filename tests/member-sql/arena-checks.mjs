// Real Arena migration against the disposable member fixtures only.
export async function arenaChecks({q,one,check,reject,migrate,asUser,principal,first,second,fair,ir,scheme,staff1,staff2,period}) {
  await asUser(principal,true)
  await migrate('20260917010000_member_arena')
  await asUser(first)
  const snapshot=await one("SELECT member_arena_snapshot($1,$2,'monthly')",[fair,period.slice(0,7)])
  const own=snapshot.people.find(p=>p.id===staff1)
  check(snapshot.membershipId,fair)
  check(snapshot.selfId,staff1)
  check(snapshot.people.length,3)
  check(Number(own.sales),7500)
  check(Number(own.held),6000)
  check(Number(own.brands.AKEMI.sales),7500)
  check(own.blindOrders,1)
  check(snapshot.people.some(p=>p.sales===0))
  check(snapshot.people.every(p=>!('salary' in p)&&!('commission' in p)&&!('points' in p)&&!('ordersList' in p)))
  check(JSON.stringify(snapshot).includes('77777'),false)
  check(snapshot.brandWeeks,null)

  // Recognition uses the release month once; carried unreleased orders are only
  // in the current open month, never added once for each queried historic month.
  const previous=await one("SELECT to_char($1::date-interval '1 month','YYYY-MM')",[period])
  const prior=await one("SELECT member_arena_snapshot($1,$2,'monthly')",[fair,previous])
  check(Number(prior.people.find(p=>p.id===staff1).sales),9000)
  check(Number(prior.people.find(p=>p.id===staff1).held),0)
  // Temporary source corrections exercise duplicate protection, a future-dated
  // current-month order, manual-margin precedence and month-end KPI eligibility.
  await asUser(principal,true)
  await q('BEGIN')
  await q('ALTER TABLE sales_orders DISABLE TRIGGER sales_orders_commission_scope')
  await q('ALTER TABLE sales_order_lines DISABLE TRIGGER sales_order_lines_commission_scope')
  const currentBatch=await one("SELECT id FROM sales_import_batches WHERE sub_department_id=$1 AND period_month=$2 AND status='committed'",[fair,period])
  const duplicate=await one("INSERT INTO sales_orders(batch_id,period_month,order_no,order_date,event_date,agent_name,agent_key,staff_id,order_total,balance,brand_code,created_at) VALUES($1,$2,'CARRIED-ORDER',$2,$2,'Agent','AGENT',$3,2500,0,'AKEMI',now()+interval '1 minute') RETURNING id",[currentBatch,period,staff1])
  await q("INSERT INTO sales_order_lines(order_id,line_no,item_group,product_code,qty,line_amount,cost_amount) VALUES($1,1,'MATTRESS','AK-MOBILE',1,2500,1500)",[duplicate])
  const future=await one("INSERT INTO sales_orders(batch_id,period_month,order_no,order_date,event_date,agent_name,agent_key,staff_id,order_total,balance,brand_code) VALUES($1,$2,'FUTURE-ARENA',(now() AT TIME ZONE 'Asia/Kuala_Lumpur')::date+1,(now() AT TIME ZONE 'Asia/Kuala_Lumpur')::date+1,'Agent','AGENT',$3,50000,0,'AKEMI') RETURNING id",[currentBatch,period,staff1])
  await q("INSERT INTO sales_order_lines(order_id,line_no,item_group,product_code,qty,line_amount,cost_amount) VALUES($1,1,'MATTRESS','AK-MOBILE',10,50000,1500)",[future])
  await asUser(first)
  check(Number((await one('SELECT member_arena_snapshot($1)',[fair])).people.find(p=>p.id===staff1).sales),7500)
  await asUser(principal,true)
  await q('UPDATE sales_orders SET manual_margin_pct=.75 WHERE id=$1',[duplicate])
  await q("UPDATE comm_kpi_items SET effective_from=($1::date+interval '1 month - 1 day')::date WHERE product_code='AK-MOBILE'",[period])
  await asUser(first)
  const corrected=(await one('SELECT member_arena_snapshot($1)',[fair])).people.find(p=>p.id===staff1)
  check(Number(corrected.marginCost),Number(own.marginCost)-1500+625)
  check(Number(corrected.kpiQty),Number(own.kpiQty))

  // Group matching follows the engine even without a KPI product fallback.
  const readOwn=async()=>{
    await asUser(first)
    return (await one('SELECT member_arena_snapshot($1)',[fair])).people.find(p=>p.id===staff1)
  }
  await asUser(principal,true)
  await q("UPDATE sales_order_lines SET item_group=' mattress ',product_code='ORDINARY' WHERE order_id=$1",[duplicate])
  check(Number((await readOwn()).sales),7500)
  // Resolve the newest document before testing its date; do not revive the old copy.
  await asUser(principal,true)
  await q("UPDATE sales_orders SET order_date=(now() AT TIME ZONE 'Asia/Kuala_Lumpur')::date+1 WHERE id=$1",[duplicate])
  check(Number((await readOwn()).sales),5000)
  await asUser(principal,true)
  await q('UPDATE sales_orders SET order_date=$2 WHERE id=$1',[duplicate,period])
  await q("UPDATE sales_order_lines SET item_group='MATTRESS',product_code='AK-MOBILE' WHERE order_id=$1",[duplicate])

  const addOrder=async(number,total,balance,amount,group='MATTRESS',code='ORDINARY',qty=1)=>{
    await asUser(principal,true)
    const id=await one("INSERT INTO sales_orders(batch_id,period_month,order_no,order_date,event_date,agent_name,agent_key,staff_id,order_total,balance,brand_code) VALUES($1,$2,$3,$2,$2,'Arena fixture','ARENA',$4,$5,$6,'AKEMI') RETURNING id",[currentBatch,period,number,staff1,total,balance])
    await q('INSERT INTO sales_order_lines(order_id,line_no,item_group,product_code,qty,line_amount,cost_amount) VALUES($1,1,$2,$3,$4,$5,0)',[id,group,code,qty,amount])
    return id
  }
  const kpiOnly=await addOrder('ARENA-KPI-ONLY',123,0,123,'TRANS','AK-MOBILE',7)
  await q('UPDATE sales_order_lines SET cost_amount=NULL WHERE order_id=$1',[kpiOnly])
  const enabled=await readOwn()
  check(Number(enabled.sales),7623)
  check(Number(enabled.kpiQty),Number(own.kpiQty)+7)
  for(const field of ['marginRevenue','marginCost','blindOrders']) check(Number(enabled[field]),Number(corrected[field]))
  await asUser(principal,true)
  await q('UPDATE comm_schemes SET enable_kpi=false WHERE id=$1',[scheme])
  const disabled=await readOwn()
  check(Number(disabled.kpiQty),0)
  check(Number(disabled.sales),7500)
  await asUser(principal,true)
  await q('UPDATE comm_schemes SET enable_kpi=true WHERE id=$1',[scheme])

  // Required deposits are rounded to cents: .50 is short of round(1.01*.5,2).
  await addOrder('ARENA-DEPOSIT-ROUND',1.01,.51,1.01)
  const rounded=await readOwn()
  check(Number(rounded.sales),Number(enabled.sales))
  check(Number(rounded.held),Number(enabled.held)+1.01)
  // Non-positive order totals bypass the gate even when paid_amount is negative.
  await addOrder('ARENA-ZERO-TOTAL',0,100,9)
  check(Number((await readOwn()).sales),Number(enabled.sales)+9)
  await addOrder('ARENA-NEGATIVE-TOTAL',-10,100,-10)
  check(Number((await readOwn()).sales),Number(enabled.sales)-1)
  await addOrder('ARENA-DISABLED-GATE',100,101,100)
  const gated=await readOwn()
  await asUser(principal,true)
  await q('UPDATE comm_schemes SET deposit_threshold_pct=NULL WHERE id=$1',[scheme])
  const ungated=await readOwn()
  check(Number(ungated.sales),Number(gated.sales)+Number(gated.held))
  check(Number(ungated.held),0)
  // Mixed orders retain goods revenue/cost even when an excluded-group KPI has
  // no cost: its quantity and sales amount count, but it is outside margin scope.
  const mixed=await addOrder('ARENA-MIXED-SCOPE',130,0,100)
  await q("INSERT INTO sales_order_lines(order_id,line_no,item_group,product_code,qty,line_amount,cost_amount) VALUES($1,2,'TRANS','AK-MOBILE',1,30,NULL)",[mixed])
  const mixedSnapshot=await readOwn()
  check(Number(mixedSnapshot.sales),Number(ungated.sales)+130)
  check(Number(mixedSnapshot.kpiQty),Number(ungated.kpiQty)+1)
  check(Number(mixedSnapshot.marginRevenue),Number(ungated.marginRevenue)+100)
  check(Number(mixedSnapshot.marginCost),Number(ungated.marginCost))
  check(Number(mixedSnapshot.blindOrders),Number(ungated.blindOrders))
  await q('ROLLBACK')
  await asUser(first)
  for(const window of ['quarterly','annual']) {
    const aggregate=await one('SELECT member_arena_snapshot($1,$2,$3)',[fair,period.slice(0,7),window])
    const months=await q("SELECT to_char(m,'YYYY-MM') AS month FROM generate_series($1::date,date_trunc('month',$2::date),'1 month') m",[aggregate.from,aggregate.through])
    const snapshots=[]
    for(const {month} of months) snapshots.push(await one("SELECT member_arena_snapshot($1,$2,'monthly')",[fair,month]))
    for(const row of aggregate.people) for(const field of ['sales','held','orders','kpiQty','marginRevenue','marginCost','blindOrders'])
      check(Number(row[field]),snapshots.reduce((sum,s)=>sum+Number(s.people.find(p=>p.id===row.id)[field]),0))
  }
  await reject("SELECT member_arena_snapshot($1,'2026-13','monthly')",[fair],/valid month/)
  await reject("SELECT member_arena_snapshot($1,$2,'weekly')",[fair,period.slice(0,7)],/valid ranking period/)
  await reject('SELECT member_arena_snapshot($1)',[ir],/not available/)
  check((await one("SELECT member_arena_snapshot($1,'2999-01')",[fair])).period,period.slice(0,7))

  const counts={AKEMI:3,ERGOTEX:0,ZANOTTI:1,DUNLOP:0}
  await q('SELECT member_arena_save_brand_weeks($1,$2,4,$3)',[fair,period.slice(0,7),JSON.stringify(counts)])
  check((await one('SELECT member_arena_snapshot($1)',[fair])).brandWeeks,{weeks:4,counts})
  await asUser(second)
  check((await one('SELECT member_arena_snapshot($1)',[fair])).brandWeeks,null)
  await asUser(first)
  await reject('SELECT member_arena_save_brand_weeks($1,$2,5,$3)',[fair,period.slice(0,7),JSON.stringify(counts)],/add up/)
  for(const invalid of [{...counts,AKEMI:-1},{...counts,AKEMI:1.5},{...counts,AKEMI:'3'},{...counts,EXTRA:0},{AKEMI:4}])
    await reject('SELECT member_arena_save_brand_weeks($1,$2,4,$3)',[fair,period.slice(0,7),JSON.stringify(invalid)],/whole numbers|four brands/)
  await reject('SELECT * FROM member_arena_brand_weeks',[],/permission denied/)
  await reject('SELECT member_arena_save_brand_weeks($1,$2,4,$3)',[ir,period.slice(0,7),JSON.stringify(counts)],/not available/)
  await asUser(principal,true)
  check(await one('SELECT staff_id FROM member_arena_brand_weeks'),staff1)
  check(await one('SELECT count(*)::integer FROM member_arena_brand_weeks'),1)
  await q("INSERT INTO user_permissions(user_id,permission_key,granted) VALUES($1,'member_insight',false)",[first])
  await asUser(first)
  await reject('SELECT member_arena_snapshot($1)',[fair],/not enabled/)
  await reject('SELECT member_arena_save_brand_weeks($1,$2,4,$3)',[fair,period.slice(0,7),JSON.stringify(counts)],/not enabled/)
  await asUser(principal,true)
  await q("DELETE FROM user_permissions WHERE user_id=$1 AND permission_key='member_insight'",[first])
  await asUser(principal)
  await reject('SELECT member_arena_snapshot($1)',[fair])
  check(!!staff2)
}
