// Builds src/lib/export/fonts/report-cjk.ts — a Noto Sans SC subset holding
// exactly the Chinese the Sales by Brand & Billing PDF prints as fixed text
// (2026-11-11). The portal's PDFs are Helvetica, which has no Chinese; a full
// CJK font is 10+ MB, too big for the worker, and no customer name in the
// ERP is written in Chinese (checked 2026-11-11: 0 of 1,818 since August),
// so the fixed words are all that need a glyph.
//
// Run after changing the report's Chinese words:
//   node tools/build-report-cjk-font.mjs
// `src/lib/export/fonts/report-cjk.test.ts` fails while a word has no glyph.
//
// The subset comes from the Google Fonts CSS API (`text=` returns a font with
// only those characters; an old user agent gets TrueType). Noto Sans SC is
// SIL Open Font License 1.1.
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCES = ['src/lib/commission/brand-billing.ts', 'src/lib/export/brand-billing-pdf.tsx']
const CJK = /[　-〿㐀-鿿＀-￯]/gu

const chars = new Set()
for (const file of SOURCES) for (const ch of readFileSync(file, 'utf8').match(CJK) ?? []) chars.add(ch)
const text = [...chars].sort().join('')

async function subset(weight) {
  const css = await fetch(
    `https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@${weight}&text=${encodeURIComponent(text)}`,
    { headers: { 'User-Agent': 'Mozilla/4.0' } },
  ).then(r => { if (!r.ok) throw new Error(`css ${r.status}`); return r.text() })
  const url = css.match(/url\((https:[^)]+)\)/)?.[1]
  if (!url) throw new Error('no font url in:\n' + css)
  const buf = Buffer.from(await fetch(url).then(r => r.arrayBuffer()))
  if (buf.readUInt32BE(0) !== 0x00010000) throw new Error(`weight ${weight}: not a TrueType font`)
  return buf
}

const regular = await subset(400)
const bold = await subset(700)
writeFileSync(
  'src/lib/export/fonts/report-cjk.ts',
  `// GENERATED by tools/build-report-cjk-font.mjs — do not edit by hand.
// Noto Sans SC (SIL Open Font License 1.1), subset to: ${text}
export const REPORT_CJK_CHARS = ${JSON.stringify(text)}
export const REPORT_CJK_REGULAR = 'data:font/ttf;base64,${regular.toString('base64')}'
export const REPORT_CJK_BOLD = 'data:font/ttf;base64,${bold.toString('base64')}'
`,
)
console.log(`${chars.size} characters · regular ${regular.length} B · bold ${bold.length} B`)
