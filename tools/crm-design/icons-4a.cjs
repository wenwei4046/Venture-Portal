// The 4a handoff's icons (docs/design_handoff_crm_redesign/icons — Lucide v0.460, MIT) as one module the screens draw
// from: src/components/member/crm/shared/icons4a.tsx. The prototypes draw them as CSS masks of the SVG files; the app
// draws the same shapes inline (currentColor, Lucide's stroke 2), so they take the colour of their text.
//   node tools/crm-design/icons-4a.cjs
const fs = require("fs"), path = require("path");
const repo = path.resolve(__dirname, "../..");
const dir = path.join(repo, "docs/design_handoff_crm_redesign/icons");
const out = {};
for (const f of fs.readdirSync(dir).filter(n => n.endsWith(".svg")).sort()) {
  const svg = fs.readFileSync(path.join(dir, f), "utf8").replace(/<metadata>[\s\S]*?<\/metadata>/, "");
  const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).replace(/\s+/g, " ").trim();
  out[f.replace(/\.svg$/, "")] = inner;
}
const code = `// GENERATED by tools/crm-design/icons-4a.cjs from docs/design_handoff_crm_redesign/icons (Lucide v0.460, MIT). Do not edit.
import type { CSSProperties } from "react";

export const ICONS_4A = ${JSON.stringify(out, null, 2)} as const;
export type Icon4a = keyof typeof ICONS_4A;

/** One of the 4a icons, drawn in its text's colour at \`size\` px (Lucide's 24 box, stroke 2 unless told). */
export function Ic({ name, size = 16, sw = 2, style }: { name: Icon4a; size?: number; sw?: number; style?: CSSProperties }) {
  return <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={sw} strokeLinecap="round" strokeLinejoin="round"
    aria-hidden="true" style={{ flex: "none", ...style }} dangerouslySetInnerHTML={{ __html: ICONS_4A[name] }} />;
}
`;
fs.writeFileSync(path.join(repo, "src/components/member/crm/shared/icons4a.tsx"), code);
console.log("icons4a", Object.keys(out).length);
