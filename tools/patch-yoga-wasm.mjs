#!/usr/bin/env node
/**
 * tools/patch-yoga-wasm.mjs   --   npm `postinstall` hook.
 *
 * WHY THIS EXISTS
 * ---------------
 * The 23 PDF export routes render through @react-pdf/renderer -> @react-pdf/layout
 * -> yoga-layout. yoga-layout 3.2.1 ships its flexbox engine as a base64 Emscripten
 * blob and calls WebAssembly.instantiate() on the decoded bytes at first render.
 * Cloudflare workerd forbids compiling WASM from runtime bytes, so every PDF route
 * returns HTTP 500 with:
 *
 *     CompileError: WebAssembly.instantiate(): Wasm code generation disallowed by embedder
 *
 * workerd DOES allow a statically imported .wasm module. This script rewrites the
 * installed yoga-layout so the engine is fed a pre-compiled WebAssembly.Module via
 * Emscripten's `instantiateWasm` hook, with the base64 path kept as a fallback for
 * plain Node (where a .wasm import cannot be resolved as an Emscripten namespace).
 *
 * The whole fix lives in node_modules, which `npm ci` erases. This script puts it
 * back on every install, on every platform.
 *
 * FOUR CHANGES, all under node_modules/yoga-layout/dist:
 *   1. binaries/yoga.wasm             NEW  - extracted from the base64 data URI in
 *                                            binaries/yoga-wasm-base64-esm.js
 *   2. binaries/yoga-wasm-module.js   NEW  - the only static `import ... from './yoga.wasm'`
 *   3. src/load.js                    PATCH- lazy dynamic import of that shim -> instantiateWasm
 *   4. src/index.js                   PATCH- route the eager default export through load.js
 *
 * WHY A SINGLE SCRIPT AND NOT patch-package
 * -----------------------------------------
 *   - Change 1 is a 71 KB binary. patch-package's diff format handles binary files
 *     badly, and a committed .wasm can silently drift from the base64 blob it was
 *     extracted from. Deriving it at install time makes drift impossible by
 *     construction: the bytes always come from the blob actually installed.
 *   - patch-package's default failure mode on a version bump is a WARNING, not a
 *     non-zero exit. `--error-on-fail` helps, but it still applies patches with
 *     fuzz, so a partially-applied patch can look like success. A silent skip on a
 *     yoga-layout upgrade is the exact disaster this file exists to prevent.
 *   - Splitting the fix across two mechanisms (patch-package for the text, a script
 *     for the binary) gives two failure modes to reason about instead of one.
 * So: one self-contained script, exact-hash gating, exit non-zero on anything
 * unexpected. Nothing is applied "with fuzz".
 *
 * PROPERTIES
 *   - Idempotent: running twice is a no-op the second time.
 *   - Fails LOUDLY (exit 1, file named, expectation named) if yoga-layout is a
 *     different version, if the base64 blob is missing/renamed/changed, or if
 *     load.js / index.js are neither pristine nor already-patched.
 *   - Pins the yoga-layout version. A human must edit PINNED_VERSION (and re-derive
 *     the hashes below) to move to a new yoga-layout.
 *   - POSIX-safe: node:fs / node:path only, forward slashes, no shell, no Windows APIs.
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

// ---------------------------------------------------------------------------
// PINS. A human edits these when yoga-layout is upgraded, after re-verifying the
// fix against the new version. Do not "fix" a mismatch by loosening a pin.
// ---------------------------------------------------------------------------
const PINNED_VERSION = '3.2.1';

// sha256 of the pristine, npm-installed files this patch was written against.
const SHA_BASE64_BLOB = '2cfeda49ae87f57bcd4a5fe433940edefc531a69bd0f83e32759fb5837df205c';
const SHA_PRISTINE_LOAD = '87c293f7926ccaabbd1026c3dce86326fa9ce02e9b216781b84b6431825b5df4';
const SHA_PRISTINE_INDEX = '0c89ff0c01ee90b081b369119f972d72f71eb8882263d94ef0824500817d5de1';

// The wasm we expect to fall out of the base64 blob.
const EXPECTED_WASM_BYTES = 71736;
const SHA_EXPECTED_WASM = '7ba9c9483c8c38a468e9aef4a95ed72fad8a43594be8e5123eb3bdb6479edf5b';

const TAG = '[patch-yoga-wasm]';

// ---------------------------------------------------------------------------
// Desired file contents. LF only, on every platform, so hashes are stable.
// ---------------------------------------------------------------------------
const WASM_SHIM_JS = [
  '// GENERATED by tools/patch-yoga-wasm.mjs -- do not edit; npm ci will overwrite it.',
  '// Static .wasm import, isolated in its own module so that Node never evaluates it.',
  "// OpenNext's esbuild marks *.wasm external and wrangler compiles it into a real",
  '// WebAssembly.Module, which is the only form workerd will accept.',
  "import yogaModule from './yoga.wasm';",
  'export default yogaModule;',
  '',
].join('\n');

const PATCHED_LOAD_JS = [
  '// PATCHED by tools/patch-yoga-wasm.mjs -- do not edit; npm ci will overwrite it.',
  "import loadYogaImpl from '../binaries/yoga-wasm-base64-esm.js';",
  "import wrapAssembly from './wrapAssembly.js';",
  '',
  'let optsPromise;',
  '',
  '// Positive identification ONLY. Anywhere we cannot prove we are in a runtime that',
  '// permits WebAssembly.instantiate(bytes), we must not fall back to the base64 blob.',
  'function isWorkersRuntime() {',
  '  try {',
  "    if (typeof navigator !== 'undefined' && navigator && navigator.userAgent === 'Cloudflare-Workers') return true;",
  '  } catch { /* navigator may throw in exotic sandboxes */ }',
  '  try {',
  "    if (typeof WebSocketPair !== 'undefined') return true;",
  '  } catch { /* not defined outside workerd */ }',
  '  return false;',
  '}',
  '',
  'async function emscriptenOpts() {',
  '  try {',
  "    // Lazy: Node's ESM loader cannot resolve a .wasm module's Emscripten import",
  '    // namespace, so this must not be a top-level static import or `next build`',
  '    // dies while collecting page data. workerd resolves it to a compiled module.',
  "    const { default: yogaModule } = await import('../binaries/yoga-wasm-module.js');",
  '    return {',
  '      instantiateWasm(imports, receiveInstance) {',
  '        const instance = new WebAssembly.Instance(yogaModule, imports);',
  '        receiveInstance(instance, yogaModule);',
  '        return instance.exports;',
  '      },',
  '    };',
  '  } catch (err) {',
  '    // The fallback below is CORRECT under Node and CATASTROPHIC under workerd:',
  '    // there, WebAssembly.instantiate() on decoded bytes is refused outright, so',
  '    // falling back trades a precise error for a misleading one -- and, worse, it',
  '    // still satisfies every static check in tools/assert-open-next-wasm.mjs,',
  '    // because those inspect the shape of the bundle and cannot see which branch',
  '    // is taken. Fail loudly where the fallback cannot work.',
  '    if (isWorkersRuntime()) {',
  '      throw new Error(',
  "        'yoga-layout: the statically imported WebAssembly module failed to load, and ' +",
  "        'this runtime forbids compiling WebAssembly from bytes, so there is no usable ' +",
  "        'fallback. Re-run `node tools/patch-yoga-wasm.mjs` and rebuild the worker. ' +",
  "        'Underlying cause: ' + (err && err.message ? err.message : String(err)),",
  '      );',
  '    }',
  '    // Node and anything else that permits it: the base64 blob works fine.',
  '    return {};',
  '  }',
  '}',
  '',
  'export async function loadYoga() {',
  '  optsPromise ??= emscriptenOpts();',
  '  return wrapAssembly(await loadYogaImpl(await optsPromise));',
  '}',
  "export * from './generated/YGEnums.js';",
  '',
].join('\n');

const PATCHED_INDEX_JS = [
  '// PATCHED by tools/patch-yoga-wasm.mjs -- do not edit; npm ci will overwrite it.',
  "import { loadYoga } from './load.js';",
  'const Yoga = await loadYoga();',
  'export default Yoga;',
  "export * from './generated/YGEnums.js';",
  '',
].join('\n');

// ---------------------------------------------------------------------------
function fail(message) {
  console.error(`\n${TAG} FAILED\n${TAG} ${message}\n`);
  console.error(
    `${TAG} This install has been failed deliberately. Shipping without this patch\n` +
      `${TAG} builds green and then returns HTTP 500 from every PDF export route in\n` +
      `${TAG} production. Fix the cause above, or re-verify the fix against the new\n` +
      `${TAG} yoga-layout and update the pins at the top of tools/patch-yoga-wasm.mjs.\n`,
  );
  process.exit(1);
}

const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

function resolveYogaRoot() {
  const require = createRequire(import.meta.url);
  // yoga-layout's exports map has no "./package.json", so resolve "." (dist/src/index.js)
  // and walk up two directories. Works with hoisting, workspaces and pnpm-style trees.
  try {
    const entry = require.resolve('yoga-layout');
    return path.resolve(path.dirname(entry), '..', '..');
  } catch {
    // Fall back to a plain node_modules lookup from the repo root.
    const here = path.dirname(fileURLToPath(import.meta.url));
    const guess = path.join(here, '..', 'node_modules', 'yoga-layout');
    if (fs.existsSync(path.join(guess, 'package.json'))) return guess;
    return null;
  }
}

// ---------------------------------------------------------------------------
function main() {
  const root = resolveYogaRoot();
  if (!root) {
    fail(
      'could not resolve the package "yoga-layout" from this repo.\n' +
        `${TAG} Expected it as a transitive dependency of @react-pdf/renderer.\n` +
        `${TAG} Expected file: <repo>/node_modules/yoga-layout/package.json`,
    );
  }

  const pkgPath = path.join(root, 'package.json');
  if (!fs.existsSync(pkgPath)) {
    fail(`missing file: ${pkgPath}\n${TAG} Expected an installed yoga-layout package here.`);
  }
  const version = JSON.parse(fs.readFileSync(pkgPath, 'utf8')).version;
  if (version !== PINNED_VERSION) {
    fail(
      `yoga-layout version mismatch.\n` +
        `${TAG}   file:     ${pkgPath}\n` +
        `${TAG}   expected: ${PINNED_VERSION}  (the version this patch was written and verified against)\n` +
        `${TAG}   found:    ${version}\n` +
        `${TAG} Re-verify the Cloudflare WASM fix against ${version}, then edit\n` +
        `${TAG} PINNED_VERSION and the sha256 pins in tools/patch-yoga-wasm.mjs.`,
    );
  }

  const binDir = path.join(root, 'dist', 'binaries');
  const srcDir = path.join(root, 'dist', 'src');
  const blobPath = path.join(binDir, 'yoga-wasm-base64-esm.js');
  const wasmPath = path.join(binDir, 'yoga.wasm');
  const shimPath = path.join(binDir, 'yoga-wasm-module.js');
  const loadPath = path.join(srcDir, 'load.js');
  const indexPath = path.join(srcDir, 'index.js');

  // -- 0. the base64 blob must be exactly what we expect ---------------------
  if (!fs.existsSync(blobPath)) {
    fail(
      `missing file: ${blobPath}\n` +
        `${TAG} Expected yoga-layout's base64 Emscripten blob. It is the source the\n` +
        `${TAG} .wasm binary is extracted from. If upstream renamed or dropped it, the\n` +
        `${TAG} patch must be rewritten.`,
    );
  }
  const blob = fs.readFileSync(blobPath, 'utf8');
  const blobSha = sha256(fs.readFileSync(blobPath));
  if (blobSha !== SHA_BASE64_BLOB) {
    fail(
      `unexpected contents: ${blobPath}\n` +
        `${TAG}   expected sha256: ${SHA_BASE64_BLOB}\n` +
        `${TAG}   found sha256:    ${blobSha}\n` +
        `${TAG} The base64 Emscripten blob changed. Re-extract and re-verify before\n` +
        `${TAG} updating SHA_BASE64_BLOB / SHA_EXPECTED_WASM / EXPECTED_WASM_BYTES.`,
    );
  }

  // -- 1. extract yoga.wasm from the data URI --------------------------------
  const uris = blob.match(/data:application\/octet-stream;base64,([A-Za-z0-9+/]+=*)/g) || [];
  const payloads = uris
    .map((u) => u.slice(u.indexOf(',') + 1))
    .filter((b64) => b64.length > 1024); // skip the literal used by the startsWith() check
  if (payloads.length !== 1) {
    fail(
      `could not locate exactly one base64 wasm payload in: ${blobPath}\n` +
        `${TAG}   expected: 1 data:application/octet-stream;base64,<...> payload longer than 1024 chars\n` +
        `${TAG}   found:    ${payloads.length}`,
    );
  }
  const wasm = Buffer.from(payloads[0], 'base64');

  const magic = [...wasm.subarray(0, 4)].map((b) => b.toString(16).padStart(2, '0')).join(' ');
  if (magic !== '00 61 73 6d') {
    fail(
      `decoded payload from ${blobPath} is not a WebAssembly module.\n` +
        `${TAG}   expected first four bytes: 00 61 73 6d\n` +
        `${TAG}   found:                     ${magic}`,
    );
  }
  if (wasm.length !== EXPECTED_WASM_BYTES) {
    fail(
      `decoded wasm has an unexpected length.\n` +
        `${TAG}   source:   ${blobPath}\n` +
        `${TAG}   expected: ${EXPECTED_WASM_BYTES} bytes\n` +
        `${TAG}   found:    ${wasm.length} bytes`,
    );
  }
  const wasmSha = sha256(wasm);
  if (wasmSha !== SHA_EXPECTED_WASM) {
    fail(
      `decoded wasm has an unexpected sha256.\n` +
        `${TAG}   source:   ${blobPath}\n` +
        `${TAG}   expected: ${SHA_EXPECTED_WASM}\n` +
        `${TAG}   found:    ${wasmSha}`,
    );
  }

  let changed = 0;
  const writeIfDifferent = (file, data, label) => {
    const existing = fs.existsSync(file) ? fs.readFileSync(file) : null;
    const want = Buffer.isBuffer(data) ? data : Buffer.from(data, 'utf8');
    if (existing && existing.equals(want)) {
      console.log(`${TAG} ok (unchanged)  ${label}`);
      return false;
    }
    fs.writeFileSync(file, want);
    console.log(`${TAG} wrote           ${label}`);
    changed += 1;
    return true;
  };

  writeIfDifferent(wasmPath, wasm, 'dist/binaries/yoga.wasm');
  writeIfDifferent(shimPath, WASM_SHIM_JS, 'dist/binaries/yoga-wasm-module.js');

  // -- 3 & 4. the two text patches, gated on exact known shapes --------------
  const patchTextFile = (file, label, pristineSha, desired) => {
    if (!fs.existsSync(file)) {
      fail(`missing file: ${file}\n${TAG} Expected yoga-layout's ${label}.`);
    }
    const current = fs.readFileSync(file, 'utf8');
    if (current === desired) {
      console.log(`${TAG} ok (unchanged)  ${label}`);
      return;
    }
    const currentSha = sha256(fs.readFileSync(file));
    if (currentSha !== pristineSha) {
      fail(
        `unexpected contents: ${file}\n` +
          `${TAG} ${label} is neither the pristine yoga-layout ${PINNED_VERSION} file nor the\n` +
          `${TAG} patched form this script produces, so it cannot be patched safely.\n` +
          `${TAG}   expected pristine sha256: ${pristineSha}\n` +
          `${TAG}   found sha256:             ${currentSha}\n` +
          `${TAG} Delete node_modules and reinstall. If upstream changed this file,\n` +
          `${TAG} re-verify the fix and update the pins in tools/patch-yoga-wasm.mjs.`,
      );
    }
    // Keep the pristine file beside the patched one for diffing / debugging.
    const orig = `${file}.orig`;
    if (!fs.existsSync(orig)) fs.writeFileSync(orig, current, 'utf8');
    fs.writeFileSync(file, desired, 'utf8');
    console.log(`${TAG} patched         ${label}`);
    changed += 1;
  };

  patchTextFile(loadPath, 'dist/src/load.js', SHA_PRISTINE_LOAD, PATCHED_LOAD_JS);
  patchTextFile(indexPath, 'dist/src/index.js', SHA_PRISTINE_INDEX, PATCHED_INDEX_JS);

  console.log(
    `${TAG} yoga-layout ${PINNED_VERSION} ready for workerd ` +
      `(${changed === 0 ? 'already applied, nothing to do' : `${changed} file(s) written`}).`,
  );
  console.log(`${TAG} root: ${root.split(path.sep).join('/')}`);
}

// Only run when executed directly (allows importing the constants from a test).
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main();
}

export { PINNED_VERSION, PATCHED_LOAD_JS, PATCHED_INDEX_JS, WASM_SHIM_JS, SHA_EXPECTED_WASM };
