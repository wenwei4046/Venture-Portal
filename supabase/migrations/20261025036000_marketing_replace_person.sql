-- 2026-10-24 — Marketing ④-5: Replace Person (`Replace Person.dc.html`; the user's answers 24–28). The manager swaps one
-- person for another wherever they stand — everything (answer 26):
--   the workflow templates     a 🔓 candidate, an approval level: a new version published at once (answer 24), the draft
--                              too (unpublished edits stay unpublished)
--   a recurring series' plan   its runs to come — doing a stage, a 🔓 candidate, approving
--   stages not started yet     doing them, a 🔓 candidate, approving them
--   the work in their hands    a stage they do now (to do / accepted: Accept again; changes asked, in review: theirs as it
--                              is) — its deadline unchanged; a subtask not yet approved
--   approval levels            on stages under way — one waiting for them now waits for the one taking over
--   the projects they own      open ones; a series' (its runs to come take its owner)
-- Anybody on the roster takes over (answer 25); a reason is asked (3–200 characters). The person replaced, the one taking
-- over and each project's owner are told (answer 27). For good — nothing goes back after a leave (answer 28). A 🔓
-- candidate or an approver the one taking over already is: the one replaced is only taken off — except an approval on a
-- stage under way, where a level would vanish: refused (untick it, or pick somebody else). Each replacement is a numbered
-- record (R-0001: what changed, what stayed, why, by whom); each project changed has its trail line ('replaced', the swap
-- in its data too — the product page's trail reads no from → to).
--
-- New: mkt_replacements — written only here, read only through these functions (RLS on, nothing granted).
-- New functions:
--   mkt_stage_people(stages)               who a template's stages name, and where (internal)
--   mkt_people_swap(list, from, to, appr)  a 🔓 candidates' or approval levels' list with one person swapped (internal)
--   mkt_cands_swap(cands, from, to)        a stage's 🔓 candidates so (internal)
--   mkt_stages_swap(stages, from, to)      a template's stages so (internal)
--   mkt_replace_scan(staff)                every place a person stands — or everybody's (internal)
--   mkt_replace_people()                   Marketing · Manage: who stands where — each person's count
--   mkt_replace_places(staff)              Marketing · Manage: one person's places
--   mkt_replace_person(from, to, keys, reason)  Marketing · Manage: the swap
-- The page: /marketing/replace (MANAGER TOOLS › 🔁), in the database's copy of the tab registry (the Tracking tab, as the
-- builders). PGlite: tests/member-sql/validate-marketing-replace.mjs.

CREATE TABLE IF NOT EXISTS public.mkt_replacements (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_staff uuid NOT NULL REFERENCES public.hr_staff_costs(id),
  to_staff   uuid NOT NULL REFERENCES public.hr_staff_costs(id),
  reason     text NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 200),
  done       jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(done) = 'array'),
  kept       jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(kept) = 'array'),
  by_user    uuid REFERENCES public.users(id),
  by_name    text NOT NULL CHECK (length(by_name) BETWEEN 1 AND 120),
  at         timestamptz NOT NULL DEFAULT now(),
  CHECK (from_staff <> to_staff)
);
ALTER TABLE public.mkt_replacements ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mkt_replacements FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.mkt_replacements_id_seq FROM anon, authenticated;
SELECT public.audit_register('mkt_replacements', 'Marketing replacements', 'Marketing', '{}', 'none',
  p_reason => 'Each replacement is its own record — written once by mkt_replace_person and never changed');

-- ── Who a template's stages name, and where ─────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.mkt_stage_people(p_stages jsonb)
RETURNS TABLE (who uuid, n integer, name text, role text)
LANGUAGE sql IMMUTABLE
SET search_path = public
AS $fn$
  SELECT lower(c)::uuid, s.n::integer, s.st ->> 'name', 'cand'::text
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(p_stages) = 'array' THEN p_stages ELSE '[]'::jsonb END)
         WITH ORDINALITY s(st, n),
         jsonb_array_elements_text(CASE WHEN jsonb_typeof(s.st -> 'who' -> 'cands') = 'array' THEN s.st -> 'who' -> 'cands'
                                        ELSE '[]'::jsonb END) c
   WHERE c ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  UNION ALL
  SELECT lower(a ->> 'staff')::uuid, s.n::integer, s.st ->> 'name', 'appr'::text
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(p_stages) = 'array' THEN p_stages ELSE '[]'::jsonb END)
         WITH ORDINALITY s(st, n),
         jsonb_array_elements(CASE WHEN jsonb_typeof(s.st -> 'appr') = 'array' THEN s.st -> 'appr' ELSE '[]'::jsonb END) a
   WHERE a ->> 'kind' = 'person'
     AND coalesce(a ->> 'staff', '') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
$fn$;

-- ── A list with one person swapped for another, never anybody twice ──────────────────
-- 🔓 candidates (p_appr false: a list of ids) or approval levels (true: a PIC's or a pick-at-assignment level as it is).
-- The one taking over listed already: the one replaced is only taken off.
CREATE OR REPLACE FUNCTION public.mkt_people_swap(p_list jsonb, p_from uuid, p_to uuid, p_appr boolean)
RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE
SET search_path = public
AS $fn$
DECLARE
  v_out jsonb := '[]'::jsonb;
  v_x   jsonb;
  v_id  text;
BEGIN
  IF jsonb_typeof(p_list) IS DISTINCT FROM 'array' THEN
    RETURN p_list;
  END IF;
  FOR v_x IN SELECT x FROM jsonb_array_elements(p_list) x LOOP
    IF p_appr THEN
      IF v_x ->> 'kind' = 'person' THEN
        v_id := lower(v_x ->> 'staff');
        IF v_id = p_from::text THEN
          v_id := p_to::text;
          v_x := v_x || jsonb_build_object('staff', v_id);
        END IF;
        CONTINUE WHEN EXISTS (SELECT 1 FROM jsonb_array_elements(v_out) o
                               WHERE o ->> 'kind' = 'person' AND lower(o ->> 'staff') = v_id);
      END IF;
    ELSE
      CONTINUE WHEN jsonb_typeof(v_x) IS DISTINCT FROM 'string';
      v_id := lower(v_x #>> '{}');
      IF v_id = p_from::text THEN
        v_id := p_to::text;
      END IF;
      CONTINUE WHEN v_out @> jsonb_build_array(v_id);
      v_x := to_jsonb(v_id);
    END IF;
    v_out := v_out || jsonb_build_array(v_x);
  END LOOP;
  RETURN v_out;
END
$fn$;

CREATE OR REPLACE FUNCTION public.mkt_cands_swap(p_cands uuid[], p_from uuid, p_to uuid)
RETURNS uuid[]
LANGUAGE sql IMMUTABLE
SET search_path = public
AS $fn$
  SELECT coalesce(array_agg(d.c ORDER BY d.n), '{}')
    FROM (SELECT u.c, min(u.n) AS n FROM unnest(array_replace(coalesce(p_cands, '{}'), p_from, p_to)) WITH ORDINALITY u(c, n)
           GROUP BY u.c) d
$fn$;

CREATE OR REPLACE FUNCTION public.mkt_stages_swap(p_stages jsonb, p_from uuid, p_to uuid)
RETURNS jsonb
LANGUAGE sql IMMUTABLE
SET search_path = public
AS $fn$
  SELECT CASE WHEN jsonb_typeof(p_stages) IS DISTINCT FROM 'array' THEN p_stages
    ELSE coalesce((
      SELECT jsonb_agg(CASE WHEN jsonb_typeof(s.st) IS DISTINCT FROM 'object' THEN s.st
                            ELSE s.st
                              || CASE WHEN jsonb_typeof(s.st -> 'who') = 'object' AND jsonb_typeof(s.st -> 'who' -> 'cands') = 'array'
                                      THEN jsonb_build_object('who', (s.st -> 'who') || jsonb_build_object('cands',
                                             public.mkt_people_swap(s.st -> 'who' -> 'cands', p_from, p_to, false)))
                                      ELSE '{}'::jsonb END
                              || CASE WHEN jsonb_typeof(s.st -> 'appr') = 'array'
                                      THEN jsonb_build_object('appr', public.mkt_people_swap(s.st -> 'appr', p_from, p_to, true))
                                      ELSE '{}'::jsonb END END
                       ORDER BY s.n)
        FROM jsonb_array_elements(p_stages) WITH ORDINALITY s(st, n)), '[]'::jsonb) END
$fn$;

-- ── Every place a person stands — or everybody's (p_staff NULL) ────────────────────────
-- grp: tpl (a template) · series (a series' plan) · up (a stage not started) · hand (a stage they do now, a subtask) ·
-- appr (an approval level on a stage under way) · own (a project). key: what the page sends back to replace it.
CREATE OR REPLACE FUNCTION public.mkt_replace_scan(p_staff uuid DEFAULT NULL)
RETURNS TABLE (staff uuid, grp text, key text, role text, ref uuid, ctx jsonb)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
  v_today date := (now() AT TIME ZONE 'Asia/Kuala_Lumpur')::date;
  v_uuid  text := '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$';
BEGIN
  -- The templates: the version published and the draft — one place a template, with every stage that names them.
  RETURN QUERY
  SELECT x.who, 'tpl'::text, 'wf:' || w.id::text, 'template'::text, w.id,
         jsonb_build_object('action', w.action, 'tname', w.tname, 'version', w.version,
                            'drafted', w.version > 0 AND w.published_rev IS DISTINCT FROM w.draft_rev,
                            'at', jsonb_agg(DISTINCT jsonb_build_object('n', x.n, 'stage', x.name, 'role', x.role)))
    FROM public.mkt_workflows w
    LEFT JOIN public.mkt_workflow_versions v ON v.workflow_id = w.id AND v.version = w.version
    CROSS JOIN LATERAL (SELECT * FROM public.mkt_stage_people(v.stages)
                        UNION
                        SELECT * FROM public.mkt_stage_people(w.draft)) x
   WHERE p_staff IS NULL OR x.who = p_staff
   GROUP BY x.who, w.id, w.action, w.tname, w.version, w.published_rev, w.draft_rev;

  -- A series' plan — its runs to come: one place a series.
  RETURN QUERY
  SELECT y.who, 'series'::text, 'series:' || p.id::text, 'series'::text, p.id,
         jsonb_build_object('track', p.track_id, 'title', p.title, 'status', p.status,
                            'at', jsonb_agg(DISTINCT jsonb_build_object('n', y.idx + 1, 'stage', y.name, 'role', y.role)))
    FROM public.mkt_projects p
    CROSS JOIN LATERAL (
      SELECT s.owner_staff AS who, s.idx, s.name, 'owner'::text AS role
        FROM public.mkt_stages s WHERE s.project_id = p.id AND s.owner_staff IS NOT NULL
      UNION ALL
      SELECT c, s.idx, s.name, 'cand' FROM public.mkt_stages s, unnest(s.cands) c WHERE s.project_id = p.id
      UNION ALL
      SELECT lower(a ->> 'staff')::uuid, s.idx, s.name, 'appr'
        FROM public.mkt_stages s, jsonb_array_elements(s.appr) a
       WHERE s.project_id = p.id AND a ->> 'kind' = 'person' AND coalesce(lower(a ->> 'staff'), '') ~ v_uuid) y
   WHERE p.kind = 'recurring' AND p.series_id IS NULL AND p.status IN ('active', 'paused')
     AND (p_staff IS NULL OR y.who = p_staff)
   GROUP BY y.who, p.id, p.track_id, p.title, p.status;

  -- A stage of an open project (a series' own plan above): doing it, a 🔓 candidate (before it starts), approving it.
  RETURN QUERY
  SELECT y.who,
         CASE WHEN s.status = 'planned' THEN 'up' WHEN y.role = 'owner' THEN 'hand' ELSE 'appr' END,
         'st:' || s.project_id::text || ':' || s.idx || ':' || y.role, y.role, s.project_id,
         jsonb_build_object('track', p.track_id, 'title', p.title, 'kind', p.kind, 'idx', s.idx, 'stage', s.name,
                            'status', s.status, 'starts', s.starts_on, 'due', s.due_on, 'ver', s.ver,
                            'late', s.due_on < v_today, 'owner', s.owner_staff, 'cands', to_jsonb(s.cands),
                            'appr', coalesce((SELECT jsonb_agg(lower(a ->> 'staff') ORDER BY k)
                                                FROM jsonb_array_elements(s.appr) WITH ORDINALITY q(a, k)
                                               WHERE a ->> 'kind' = 'person'), '[]'::jsonb),
                            'level', y.lvl,
                            'waiting', s.status = 'review' AND y.role = 'appr' AND y.lvl = s.appr_idx + 1)
    FROM public.mkt_stages s
    JOIN public.mkt_projects p ON p.id = s.project_id
    CROSS JOIN LATERAL (
      SELECT s.owner_staff AS who, 'owner'::text AS role, NULL::integer AS lvl WHERE s.owner_staff IS NOT NULL
      UNION ALL
      SELECT c, 'cand', NULL FROM unnest(s.cands) c WHERE s.status = 'planned'
      UNION ALL
      SELECT lower(a ->> 'staff')::uuid, 'appr', k::integer
        FROM jsonb_array_elements(s.appr) WITH ORDINALITY q(a, k)
       WHERE a ->> 'kind' = 'person' AND coalesce(lower(a ->> 'staff'), '') ~ v_uuid) y
   WHERE s.status <> 'done' AND p.status NOT IN ('done', 'cancelled')
     AND NOT (p.kind = 'recurring' AND p.series_id IS NULL)
     AND (p_staff IS NULL OR y.who = p_staff);

  -- A subtask not yet approved.
  RETURN QUERY
  SELECT t.assignee, 'hand'::text, 'sub:' || t.id::text, 'subtask'::text, t.project_id,
         jsonb_build_object('track', p.track_id, 'title', p.title, 'kind', p.kind, 'idx', t.stage_idx, 'stage', s.name,
                            'subtask', t.title, 'status', t.status, 'due', t.due_on, 'late', t.due_on < v_today)
    FROM public.mkt_subtasks t
    JOIN public.mkt_projects p ON p.id = t.project_id
    JOIN public.mkt_stages s ON s.project_id = t.project_id AND s.idx = t.stage_idx
   WHERE t.status <> 'approved' AND p.status NOT IN ('done', 'cancelled')
     AND (p_staff IS NULL OR t.assignee = p_staff);

  -- A project they own, still open (a series too).
  RETURN QUERY
  SELECT p.owner_staff, 'own'::text, 'own:' || p.id::text, 'project'::text, p.id,
         jsonb_build_object('track', p.track_id, 'title', p.title, 'kind', p.kind, 'status', p.status, 'due', p.due_on,
                            'series', p.kind = 'recurring' AND p.series_id IS NULL)
    FROM public.mkt_projects p
   WHERE p.owner_staff IS NOT NULL AND p.status NOT IN ('done', 'cancelled')
     AND (p_staff IS NULL OR p.owner_staff = p_staff);
END
$fn$;

-- ── Who stands where: each person's count (anybody with a place — on the roster or not) ─────────
CREATE OR REPLACE FUNCTION public.mkt_replace_people()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public
AS $fn$
BEGIN
  PERFORM public.mkt_need(ARRAY['marketing.manage'], 'Replace Person is the manager''s.');
  RETURN coalesce((
    SELECT jsonb_agg(jsonb_build_object('id', x.staff, 'full', s.employee_name,
                                        'first', coalesce(nullif(btrim(s.first_name), ''), split_part(btrim(s.employee_name), ' ', 1)),
                                        'places', x.n)
                     ORDER BY x.n DESC, s.employee_name)
      FROM (SELECT r.staff, count(*)::integer AS n FROM public.mkt_replace_scan(NULL) r GROUP BY r.staff) x
      JOIN public.hr_staff_costs s ON s.id = x.staff), '[]'::jsonb);
END
$fn$;

-- ── One person's places ────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.mkt_replace_places(p_staff uuid)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
  v_full  text;
  v_first text;
BEGIN
  PERFORM public.mkt_need(ARRAY['marketing.manage'], 'Replace Person is the manager''s.');
  SELECT s.employee_name, coalesce(nullif(btrim(s.first_name), ''), split_part(btrim(s.employee_name), ' ', 1))
    INTO v_full, v_first
    FROM public.hr_staff_costs s WHERE s.id = p_staff;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  RETURN jsonb_build_object(
    'person', jsonb_build_object('id', p_staff, 'full', v_full, 'first', v_first),
    'places', coalesce((SELECT jsonb_agg(r.ctx || jsonb_build_object('key', r.key, 'grp', r.grp, 'role', r.role, 'ref', r.ref)
                                         ORDER BY r.grp, coalesce(r.ctx ->> 'track', r.ctx ->> 'action'), r.key)
                          FROM public.mkt_replace_scan(p_staff) r), '[]'::jsonb));
END
$fn$;

-- ── The swap ──────────────────────────────────────────────────────────────────────
-- Each place ticked, if still theirs (one no longer theirs is skipped — counted as gone); the rest stays with them.
CREATE OR REPLACE FUNCTION public.mkt_replace_person(p_from uuid, p_to uuid, p_keys text[], p_reason text)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
  v_reason text := btrim(coalesce(p_reason, ''));
  v_keys   text[];
  v_from   text;
  v_to     text;
  v_places jsonb;
  v_pl     jsonb;
  v_key    text;
  v_role   text;
  v_id     uuid;
  v_idx    integer;
  v_dupe   boolean;
  v_new    boolean;
  v_rec    bigint;
  v_done   jsonb := '[]'::jsonb;
  v_kept   jsonb;
  v_gone   integer := 0;
  v_tell   jsonb := '{}'::jsonb;
  v_rank   integer;
  v_w      public.mkt_workflows;
  v_v      public.mkt_workflow_versions;
  v_s      public.mkt_stages;
  v_stages jsonb;
  v_draft  jsonb;
  v_owner  uuid;
  v_title  text;
BEGIN
  PERFORM public.mkt_need(ARRAY['marketing.manage'], 'Replace Person is the manager''s.');
  IF p_from IS NULL OR p_to IS NULL THEN
    RAISE EXCEPTION 'Pick who is replaced and who takes over.' USING ERRCODE = '22023';
  END IF;
  IF p_from = p_to THEN
    RAISE EXCEPTION 'Pick somebody else to take over.' USING ERRCODE = '22023';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.mkt_roster() r WHERE r.staff_id = p_to) THEN
    RAISE EXCEPTION 'Only somebody on Marketing''s roster takes over.' USING ERRCODE = '22023';
  END IF;
  IF length(v_reason) NOT BETWEEN 3 AND 200 THEN
    RAISE EXCEPTION 'Say why — 3 to 200 characters.' USING ERRCODE = '22023';
  END IF;
  v_keys := ARRAY(SELECT DISTINCT k FROM unnest(coalesce(p_keys, '{}')) k WHERE k IS NOT NULL AND length(k) <= 120);
  IF cardinality(v_keys) = 0 THEN
    RAISE EXCEPTION 'Tick at least one place.' USING ERRCODE = '22023';
  END IF;
  IF cardinality(v_keys) > 2000 THEN
    RAISE EXCEPTION 'Too many places at once.' USING ERRCODE = '22023';
  END IF;
  -- One replacement at a time: each reads where the person stands as the one before left it.
  PERFORM pg_advisory_xact_lock(hashtext('mkt_replace_person'));
  v_from := coalesce(public.mkt_staff_name(p_from), 'Somebody');
  v_to := public.mkt_staff_name(p_to);

  -- Where they stand now.
  SELECT coalesce(jsonb_object_agg(r.key, r.ctx || jsonb_build_object('key', r.key, 'grp', r.grp, 'role', r.role, 'ref', r.ref)),
                  '{}'::jsonb)
    INTO v_places
    FROM public.mkt_replace_scan(p_from) r;

  -- Refused before anything changes: an approval on a stage under way that the one taking over holds already — a level
  -- would vanish under somebody's feet.
  FOREACH v_key IN ARRAY v_keys LOOP
    v_pl := v_places -> v_key;
    IF v_pl ->> 'grp' = 'appr' AND (v_pl -> 'appr') ? p_to::text THEN
      RAISE EXCEPTION '% already approves % on % — untick it, or pick somebody else.', v_to, v_pl ->> 'stage', v_pl ->> 'track'
        USING ERRCODE = '22023';
    END IF;
  END LOOP;

  -- Nothing ticked is theirs any more: refused before the record takes a number (the numbers run without gaps).
  IF NOT EXISTS (SELECT 1 FROM unnest(v_keys) k WHERE v_places ? k) THEN
    RAISE EXCEPTION 'None of those places is %''s any more — reload to see where they stand.', v_from USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.mkt_replacements (from_staff, to_staff, reason, by_user, by_name)
  VALUES (p_from, p_to, v_reason, auth.uid(), public.mkt_actor())
  RETURNING id INTO v_rec;

  FOREACH v_key IN ARRAY v_keys LOOP
    v_pl := v_places -> v_key;
    IF v_pl IS NULL THEN
      v_gone := v_gone + 1;
      CONTINUE;
    END IF;
    v_role := v_pl ->> 'role';
    v_id := (v_pl ->> 'ref')::uuid;
    v_dupe := false;
    v_new := false;
    v_rank := 1;

    IF v_pl ->> 'grp' = 'tpl' THEN
      -- A template: a new version published at once (answer 24); the draft too.
      SELECT * INTO v_w FROM public.mkt_workflows WHERE id = v_id FOR UPDATE;
      v_draft := public.mkt_stages_swap(v_w.draft, p_from, p_to);
      IF v_w.version > 0 THEN
        SELECT * INTO v_v FROM public.mkt_workflow_versions WHERE workflow_id = v_w.id AND version = v_w.version;
        v_stages := public.mkt_stages_swap(v_v.stages, p_from, p_to);
        IF v_stages IS DISTINCT FROM v_v.stages THEN
          INSERT INTO public.mkt_workflow_versions (workflow_id, version, stages, canvas, locked, promise, published_by)
          VALUES (v_w.id, v_w.version + 1, v_stages, v_v.canvas, v_v.locked, v_v.promise, auth.uid());
          v_new := true;
        END IF;
      END IF;
      UPDATE public.mkt_workflows
         SET draft = v_draft,
             draft_rev = CASE WHEN v_draft IS DISTINCT FROM v_w.draft THEN v_w.draft_rev + 1 ELSE v_w.draft_rev END,
             version = CASE WHEN v_new THEN v_w.version + 1 ELSE v_w.version END,
             -- A draft that was the version published stays it; one with edits of its own keeps them unpublished.
             published_rev = CASE WHEN v_new AND v_w.published_rev = v_w.draft_rev
                                  THEN CASE WHEN v_draft IS DISTINCT FROM v_w.draft THEN v_w.draft_rev + 1 ELSE v_w.draft_rev END
                                  ELSE v_w.published_rev END,
             updated_by = auth.uid(), updated_at = now()
       WHERE id = v_w.id;
      v_done := v_done || jsonb_build_array(v_pl || jsonb_build_object('published', CASE WHEN v_new THEN v_w.version + 1 END));
      CONTINUE;
    END IF;

    IF v_pl ->> 'grp' = 'series' THEN
      -- A series' plan: every stage that names them — its runs to come.
      UPDATE public.mkt_stages s
         SET owner_staff = CASE WHEN s.owner_staff = p_from THEN p_to ELSE s.owner_staff END,
             cands = public.mkt_cands_swap(s.cands, p_from, p_to),
             appr = public.mkt_people_swap(s.appr, p_from, p_to, true)
       WHERE s.project_id = v_id;
      PERFORM public.mkt_log(v_id, 'replaced', NULL, NULL, v_from || ' → ' || v_to, v_reason,
                p_data => jsonb_build_object('role', 'series', 'rec', v_rec, 'swap', v_from || ' → ' || v_to));
    ELSIF v_key LIKE 'st:%' THEN
      v_idx := (v_pl ->> 'idx')::integer;
      SELECT * INTO v_s FROM public.mkt_stages WHERE project_id = v_id AND idx = v_idx FOR UPDATE;
      IF v_role = 'owner' THEN
        -- Doing it: one to do or accepted is theirs to Accept again; its deadline stays.
        IF v_s.status IN ('todo', 'accepted') THEN
          v_rank := 3;
        END IF;
        UPDATE public.mkt_stages
           SET owner_staff = p_to,
               status = CASE WHEN status IN ('todo', 'accepted') THEN 'todo' ELSE status END,
               entered_at = CASE WHEN status IN ('todo', 'accepted') THEN now() ELSE entered_at END,
               accepted_at = CASE WHEN status IN ('todo', 'accepted') THEN NULL ELSE accepted_at END
         WHERE project_id = v_id AND idx = v_idx;
      ELSIF v_role = 'cand' THEN
        v_dupe := p_to = ANY (v_s.cands);
        UPDATE public.mkt_stages SET cands = public.mkt_cands_swap(cands, p_from, p_to) WHERE project_id = v_id AND idx = v_idx;
      ELSE
        v_dupe := EXISTS (SELECT 1 FROM jsonb_array_elements(v_s.appr) a
                           WHERE a ->> 'kind' = 'person' AND lower(a ->> 'staff') = p_to::text);
        IF (v_pl ->> 'waiting')::boolean THEN
          v_rank := 2;
        END IF;
        UPDATE public.mkt_stages SET appr = public.mkt_people_swap(appr, p_from, p_to, true)
         WHERE project_id = v_id AND idx = v_idx;
      END IF;
      PERFORM public.mkt_log(v_id, 'replaced', v_idx, v_s.name, v_from || ' → ' || v_to, v_reason,
                p_data => jsonb_build_object('role', v_role, 'rec', v_rec, 'dupe', v_dupe, 'swap', v_from || ' → ' || v_to));
    ELSIF v_key LIKE 'sub:%' THEN
      UPDATE public.mkt_subtasks SET assignee = p_to, updated_at = now()
       WHERE id = split_part(v_key, ':', 2)::uuid AND assignee = p_from;
      PERFORM public.mkt_log(v_id, 'replaced', (v_pl ->> 'idx')::integer, v_pl ->> 'stage', v_from || ' → ' || v_to, v_reason,
                p_data => jsonb_build_object('role', 'subtask', 'rec', v_rec, 'subtask', v_pl ->> 'subtask', 'swap', v_from || ' → ' || v_to));
    ELSE
      UPDATE public.mkt_projects SET owner_staff = p_to WHERE id = v_id AND owner_staff = p_from;
      PERFORM public.mkt_log(v_id, 'replaced', NULL, NULL, v_from || ' → ' || v_to, v_reason,
                p_data => jsonb_build_object('role', 'project', 'rec', v_rec, 'swap', v_from || ' → ' || v_to));
    END IF;
    UPDATE public.mkt_projects SET updated_at = now() WHERE id = v_id;
    v_done := v_done || jsonb_build_array(v_pl || jsonb_build_object('dupe', v_dupe));
    -- Whom the project's notice to the one taking over speaks of: a stage of theirs now (3), an approval waiting (2), or
    -- that they took over (1).
    IF coalesce((v_tell -> v_id::text ->> 'rank')::integer, 0) < v_rank THEN
      v_tell := v_tell || jsonb_build_object(v_id::text, jsonb_build_object('rank', v_rank, 'stage', v_pl ->> 'stage',
                  'ver', v_pl ->> 'ver'));
    END IF;
  END LOOP;

  -- Told (answer 27): the one taking over, the one replaced, and each project's owner — once a project.
  FOR v_id, v_pl IN SELECT e.key::uuid, e.value FROM jsonb_each(v_tell) e LOOP
    SELECT p.title, p.owner_staff INTO v_title, v_owner FROM public.mkt_projects p WHERE p.id = v_id;
    PERFORM public.mkt_notify(p_to, v_id,
              CASE (v_pl ->> 'rank')::integer
                WHEN 3 THEN 'Your turn: ' || (v_pl ->> 'stage')
                WHEN 2 THEN (v_pl ->> 'stage') || ' v' || (v_pl ->> 'ver') || ' waits for your approval'
                ELSE 'You took over from ' || v_from || ': ' || v_title END,
              (SELECT p.track_id FROM public.mkt_projects p WHERE p.id = v_id) || ' · ' || v_title || ' — "' || v_reason || '"',
              CASE (v_pl ->> 'rank')::integer WHEN 3 THEN 'open' WHEN 2 THEN 'review' ELSE 'task' END);
    PERFORM public.mkt_notify(p_from, v_id, v_title || ': ' || v_to || ' took over', '"' || v_reason || '"', 'task');
    IF v_owner IS NOT NULL AND v_owner <> p_from AND v_owner <> p_to THEN
      PERFORM public.mkt_notify(v_owner, v_id, v_from || ' → ' || v_to || ' on "' || v_title || '"', '"' || v_reason || '"', 'task');
    END IF;
  END LOOP;

  -- What stayed with them: their places not ticked.
  SELECT coalesce(jsonb_agg(e.value ORDER BY e.value ->> 'grp', e.value ->> 'track', e.key), '[]'::jsonb) INTO v_kept
    FROM jsonb_each(v_places) e
   WHERE NOT (e.key = ANY (v_keys));
  UPDATE public.mkt_replacements SET done = v_done, kept = v_kept WHERE id = v_rec;

  RETURN jsonb_build_object('rec', v_rec, 'at', now(), 'by', public.mkt_actor(),
    'from', jsonb_build_object('id', p_from, 'first', v_from), 'to', jsonb_build_object('id', p_to, 'first', v_to),
    'reason', v_reason, 'done', v_done, 'kept', v_kept, 'gone', v_gone);
END
